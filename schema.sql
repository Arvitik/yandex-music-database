BEGIN;
CREATE TABLE genre (
    genre_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name varchar(100) NOT NULL UNIQUE CHECK (btrim(genre_name) <> '')
);

CREATE TABLE preference (
    preference_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_id integer NOT NULL UNIQUE REFERENCES genre ON DELETE RESTRICT
);

CREATE TABLE subscriptions (
    subscriptions_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscriptions_type varchar(100) NOT NULL UNIQUE,
    price numeric(10,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name varchar(255) NOT NULL CHECK (btrim(user_name) <> ''),
    age integer NOT NULL CHECK (age BETWEEN 0 AND 120),
    preference_id integer NOT NULL REFERENCES preference ON DELETE RESTRICT,
    subscriptions_id integer NOT NULL REFERENCES subscriptions ON DELETE RESTRICT
);

CREATE TABLE artist (
    artist_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    photo varchar(255) NOT NULL DEFAULT '',
    genre_id integer NOT NULL REFERENCES genre ON DELETE RESTRICT,
    artist_name varchar(255) NOT NULL CHECK (btrim(artist_name) <> '')
);

CREATE TABLE album (
    album_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_name varchar(255) NOT NULL CHECK (btrim(album_name) <> ''),
    release_id date NOT NULL,
    artist_id integer NOT NULL REFERENCES artist ON DELETE RESTRICT,
    genre_id integer NOT NULL REFERENCES genre ON DELETE RESTRICT
);

CREATE TABLE song (
    song_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating numeric(3,2) CHECK (rating BETWEEN 0 AND 5),
    play_count bigint NOT NULL DEFAULT 0 CHECK (play_count >= 0),
    song_name varchar(255) NOT NULL CHECK (btrim(song_name) <> ''),
    duration interval NOT NULL CHECK (duration > interval '0 seconds'),
    album_id integer NOT NULL REFERENCES album ON DELETE RESTRICT,
    artist_id integer NOT NULL REFERENCES artist ON DELETE RESTRICT,
    genre_id integer NOT NULL REFERENCES genre ON DELETE RESTRICT
);

CREATE TABLE album_artist (
    album_artist_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id integer NOT NULL REFERENCES album ON DELETE CASCADE,
    artist_id integer NOT NULL REFERENCES artist ON DELETE RESTRICT,
    UNIQUE (album_id, artist_id)
);

CREATE TABLE song_artist (
    song_artist_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_id integer NOT NULL REFERENCES song ON DELETE CASCADE,
    artist_id integer NOT NULL REFERENCES artist ON DELETE RESTRICT,
    UNIQUE (song_id, artist_id)
);

CREATE TABLE song_genre (
    song_genre_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_id integer NOT NULL REFERENCES song ON DELETE CASCADE,
    genre_id integer NOT NULL REFERENCES genre ON DELETE RESTRICT,
    UNIQUE (song_id, genre_id)
);

CREATE TABLE playlist (
    playlist_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_name varchar(255) NOT NULL CHECK (btrim(playlist_name) <> ''),
    description text NOT NULL DEFAULT '',
    creation_time date NOT NULL DEFAULT current_date
);

CREATE TABLE playlist_song (
    playlist_song_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id integer NOT NULL REFERENCES playlist ON DELETE CASCADE,
    song_id integer NOT NULL REFERENCES song ON DELETE CASCADE,
    position integer NOT NULL CHECK (position > 0),
    UNIQUE (playlist_id, song_id),
    UNIQUE (playlist_id, position) DEFERRABLE INITIALLY IMMEDIATE
);

CREATE TABLE playlist_user (
    playlist_user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id integer NOT NULL REFERENCES playlist ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
    UNIQUE (playlist_id, user_id)
);

CREATE TABLE recommendation (
    recommendation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
    song_id integer NOT NULL REFERENCES song ON DELETE CASCADE,
    preference_id integer NOT NULL REFERENCES preference ON DELETE RESTRICT,
    reason text NOT NULL DEFAULT 'Preferred genre',
    UNIQUE (user_id, song_id)
);

CREATE TABLE recommendation_user (
    recommendation_user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id integer NOT NULL REFERENCES recommendation ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
    UNIQUE (recommendation_id, user_id)
);

CREATE TABLE events (
    event_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name varchar(255) NOT NULL CHECK (btrim(event_name) <> ''),
    date timestamptz NOT NULL,
    geolocation varchar(255) NOT NULL,
    description text NOT NULL DEFAULT '',
