CREATE FUNCTION generate_demo_data(p_scale integer DEFAULT 1)
RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE u integer; a integer; al integer; s integer; pl integer; ev integer;
BEGIN
    IF p_scale IS NULL OR p_scale NOT BETWEEN 1 AND 1000 THEN
        RAISE EXCEPTION 'Scale must be between 1 and 1000';
    END IF;
    PERFORM pg_advisory_xact_lock(171802);
    LOCK TABLE users, artist, album, song, playlist, events IN SHARE ROW EXCLUSIVE MODE;
    SELECT coalesce(max(user_id), 0) INTO u FROM users;
    SELECT coalesce(max(artist_id), 0) INTO a FROM artist;
    SELECT coalesce(max(album_id), 0) INTO al FROM album;
    SELECT coalesce(max(song_id), 0) INTO s FROM song;
    SELECT coalesce(max(playlist_id), 0) INTO pl FROM playlist;
    SELECT coalesce(max(event_id), 0) INTO ev FROM events;

    INSERT INTO users(user_id, user_name, age, preference_id, subscriptions_id)
    SELECT u+i, format('Listener %s', u+i), 16+i%45, 1+(i-1)%6, 1+(i-1)%4
    FROM generate_series(1, 40*p_scale) i;
    INSERT INTO subscriptions_users(user_id, subscriptions_id, start_date, end_date)
    SELECT u+i, 1+(i-1)%4, current_date-15, current_date+15
    FROM generate_series(1, 40*p_scale) i;
    INSERT INTO artist(artist_id, photo, genre_id, artist_name)
    SELECT a+i, format('https://example.test/artists/%s.jpg', a+i), 1+(i-1)%6,
           format('Artist %s', a+i)
    FROM generate_series(1, 12*p_scale) i;
    INSERT INTO album(album_id, album_name, release_id, artist_id, genre_id)
    SELECT al+i, format('Album %s', al+i), current_date-i*7,
           a+1+(i-1)%(12*p_scale), 1+(i-1)%6
    FROM generate_series(1, 24*p_scale) i;
    INSERT INTO song(song_id, song_name, duration, album_id, artist_id, genre_id)
    SELECT s+i, format('Song %s', s+i), (120+i%180)*interval '1 second',
           alb.album_id, alb.artist_id, alb.genre_id
    FROM generate_series(1, 120*p_scale) i
    JOIN album alb ON alb.album_id = al+1+(i-1)%(24*p_scale);
    INSERT INTO song_artist(song_id, artist_id)
    SELECT s+i, a+1+i%(12*p_scale) FROM generate_series(6, 120*p_scale, 6) i
    ON CONFLICT DO NOTHING;
    INSERT INTO album_artist(album_id, artist_id)
    SELECT al+i, a+1+i%(12*p_scale) FROM generate_series(4, 24*p_scale, 4) i
    ON CONFLICT DO NOTHING;
    INSERT INTO playlist(playlist_id, playlist_name, description)
    SELECT pl+i, format('Playlist %s', pl+i), 'Synthetic demo playlist'
    FROM generate_series(1, 40*p_scale) i;
    INSERT INTO playlist_user(playlist_id, user_id)
    SELECT pl+i, u+i FROM generate_series(1, 40*p_scale) i;
    INSERT INTO playlist_song(playlist_id, song_id, position)
    SELECT pl+i, s+1+((i-1)*3+j)%(120*p_scale), j+1
    FROM generate_series(1, 38*p_scale) i CROSS JOIN generate_series(0, 5) j;
    INSERT INTO events(event_id, event_name, date, geolocation, description, artist_id)
    SELECT ev+i, format('Concert %s', ev+i), current_timestamp+i*interval '1 day',
           format('Demo venue %s', i), 'Synthetic event', a+1+(i-1)%(12*p_scale)
    FROM generate_series(1, 12*p_scale) i;
    INSERT INTO song_user(user_id, song_id, listened_at)
    SELECT u+1+(i-1)%(40*p_scale), s+1+(i*7)%(120*p_scale),
           current_timestamp-i*interval '1 minute'
    FROM generate_series(1, 360*p_scale) i;
    INSERT INTO song_rating(user_id, song_id, rating)
    SELECT u+1+(i-1)%(40*p_scale), s+i, (2+(i%7)*0.5)::numeric(3,2)
    FROM generate_series(1, 120*p_scale) i;
    PERFORM refresh_recommendations(u+i, 10) FROM generate_series(1, 40*p_scale) i;

    PERFORM setval(pg_get_serial_sequence('users','user_id'), (SELECT max(user_id) FROM users));
    PERFORM setval(pg_get_serial_sequence('artist','artist_id'), (SELECT max(artist_id) FROM artist));
    PERFORM setval(pg_get_serial_sequence('album','album_id'), (SELECT max(album_id) FROM album));
    PERFORM setval(pg_get_serial_sequence('song','song_id'), (SELECT max(song_id) FROM song));
    PERFORM setval(pg_get_serial_sequence('playlist','playlist_id'), (SELECT max(playlist_id) FROM playlist));
    PERFORM setval(pg_get_serial_sequence('events','event_id'), (SELECT max(event_id) FROM events));
    RETURN jsonb_build_object('users', 40*p_scale, 'artists', 12*p_scale,
        'albums', 24*p_scale, 'songs', 120*p_scale, 'playlists', 40*p_scale);
END;
$$;

