CREATE TABLE song_rating (
    user_id integer NOT NULL REFERENCES users ON DELETE CASCADE,
    song_id integer NOT NULL REFERENCES song ON DELETE CASCADE,
    rating numeric(3,2) NOT NULL CHECK (rating BETWEEN 0 AND 5),
    PRIMARY KEY (user_id, song_id)
);

CREATE INDEX song_rating_song_idx ON song_rating (song_id);

CREATE FUNCTION synchronize_primary_links() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    CASE TG_TABLE_NAME
    WHEN 'album' THEN
        INSERT INTO album_artist(album_id, artist_id) VALUES (NEW.album_id, NEW.artist_id)
        ON CONFLICT (album_id, artist_id) DO NOTHING;
    WHEN 'song' THEN
        INSERT INTO song_artist(song_id, artist_id) VALUES (NEW.song_id, NEW.artist_id)
        ON CONFLICT (song_id, artist_id) DO NOTHING;
        INSERT INTO song_genre(song_id, genre_id) VALUES (NEW.song_id, NEW.genre_id)
        ON CONFLICT (song_id, genre_id) DO NOTHING;
    WHEN 'events' THEN
        INSERT INTO artist_event(event_id, artist_id) VALUES (NEW.event_id, NEW.artist_id)
        ON CONFLICT (artist_id, event_id) DO NOTHING;
    WHEN 'recommendation' THEN
        IF TG_OP = 'UPDATE' AND OLD.user_id <> NEW.user_id THEN
            DELETE FROM recommendation_user
            WHERE recommendation_id = NEW.recommendation_id AND user_id = OLD.user_id;
        END IF;
        INSERT INTO recommendation_user(recommendation_id, user_id)
        VALUES (NEW.recommendation_id, NEW.user_id)
        ON CONFLICT (recommendation_id, user_id) DO NOTHING;
    END CASE;
    RETURN NULL;
END;
$$;

CREATE TRIGGER album_primary_links AFTER INSERT OR UPDATE OF artist_id ON album
FOR EACH ROW EXECUTE FUNCTION synchronize_primary_links();
CREATE TRIGGER song_primary_links AFTER INSERT OR UPDATE OF artist_id, genre_id ON song
FOR EACH ROW EXECUTE FUNCTION synchronize_primary_links();
CREATE TRIGGER event_primary_links AFTER INSERT OR UPDATE OF artist_id ON events
FOR EACH ROW EXECUTE FUNCTION synchronize_primary_links();
CREATE TRIGGER recommendation_primary_links AFTER INSERT OR UPDATE OF user_id ON recommendation
FOR EACH ROW EXECUTE FUNCTION synchronize_primary_links();

CREATE FUNCTION update_song_statistics() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE target integer;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'Listening history is append-only; delete and insert instead';
    END IF;
    IF TG_OP = 'DELETE' THEN
        target := OLD.song_id;
        UPDATE song SET play_count = play_count-1 WHERE song_id = target;
    ELSE
        target := NEW.song_id;
        UPDATE song SET play_count = play_count+1 WHERE song_id = target;
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER song_listening_statistics AFTER INSERT OR UPDATE OR DELETE ON song_user
FOR EACH ROW EXECUTE FUNCTION update_song_statistics();

CREATE FUNCTION update_song_rating() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.song_id <> NEW.song_id THEN
        PERFORM song_id FROM song WHERE song_id IN (OLD.song_id, NEW.song_id)
        ORDER BY song_id FOR UPDATE;
        UPDATE song SET rating = (SELECT round(avg(rating), 2) FROM song_rating
            WHERE song_id = OLD.song_id) WHERE song_id = OLD.song_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        PERFORM song_id FROM song WHERE song_id = OLD.song_id FOR UPDATE;
        UPDATE song SET rating = (SELECT round(avg(rating), 2) FROM song_rating
            WHERE song_id = OLD.song_id) WHERE song_id = OLD.song_id;
    ELSE
        PERFORM song_id FROM song WHERE song_id = NEW.song_id FOR UPDATE;
        UPDATE song SET rating = (SELECT round(avg(rating), 2) FROM song_rating
            WHERE song_id = NEW.song_id) WHERE song_id = NEW.song_id;
    END IF;
    RETURN NULL;
END;
$$;

CREATE TRIGGER song_rating_statistics AFTER INSERT OR UPDATE OR DELETE ON song_rating
FOR EACH ROW EXECUTE FUNCTION update_song_rating();

CREATE FUNCTION add_song_to_playlist(p_playlist integer, p_song integer)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE result integer; next_position integer;
BEGIN
    PERFORM 1 FROM playlist WHERE playlist_id = p_playlist FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Playlist does not exist'; END IF;
    SELECT coalesce(max(position), 0)+1 INTO next_position
    FROM playlist_song WHERE playlist_id = p_playlist;
    INSERT INTO playlist_song(playlist_id, song_id, position)
    VALUES (p_playlist, p_song, next_position)
    RETURNING playlist_song_id INTO result;
    RETURN result;
END;
$$;

CREATE FUNCTION record_listen(p_user integer, p_song integer)
RETURNS bigint LANGUAGE sql AS $$
    INSERT INTO song_user(user_id, song_id) VALUES (p_user, p_song)
    RETURNING song_user_id;
$$;

CREATE FUNCTION rate_song(p_user integer, p_song integer, p_rating numeric)
RETURNS void LANGUAGE sql AS $$
    INSERT INTO song_rating(user_id, song_id, rating) VALUES (p_user, p_song, p_rating)
    ON CONFLICT (user_id, song_id) DO UPDATE SET rating = excluded.rating;
$$;

CREATE FUNCTION refresh_recommendations(p_user integer, p_limit integer DEFAULT 10)
RETURNS integer LANGUAGE plpgsql AS $$
DECLARE result integer;
BEGIN
    IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 100 THEN
        RAISE EXCEPTION 'Limit must be between 1 and 100';
    END IF;
    PERFORM 1 FROM users WHERE user_id = p_user FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'User does not exist'; END IF;
    DELETE FROM recommendation WHERE user_id = p_user;
    INSERT INTO recommendation(user_id, song_id, preference_id, reason)
    SELECT u.user_id, s.song_id, u.preference_id, 'Preferred genre; not listened to yet'
    FROM users u JOIN preference pr USING (preference_id)
    JOIN song_genre sg ON sg.genre_id = pr.genre_id
    JOIN song s USING (song_id)
    WHERE u.user_id = p_user AND NOT EXISTS (
        SELECT 1 FROM song_user su WHERE su.user_id = p_user AND su.song_id = s.song_id
    )
    ORDER BY s.rating DESC NULLS LAST, s.play_count DESC, s.song_id
    LIMIT p_limit;
    GET DIAGNOSTICS result = ROW_COUNT;
    RETURN result;
END;
$$;

CREATE VIEW playlist_details AS
SELECT p.playlist_id, p.playlist_name, p.description, p.creation_time,
       count(ps.song_id) AS song_count,
       coalesce(sum(s.duration), interval '0 seconds') AS total_duration,
       coalesce(string_agg(s.song_name, ', ' ORDER BY ps.position), '') AS track_list
FROM playlist p LEFT JOIN playlist_song ps USING (playlist_id)
LEFT JOIN song s USING (song_id)
GROUP BY p.playlist_id;

CREATE VIEW active_subscriptions AS
SELECT su.subscriptions_users_id, u.user_id, u.user_name,
       s.subscriptions_type, s.price, su.start_date, su.end_date
FROM subscriptions_users su JOIN users u USING (user_id)
JOIN subscriptions s ON s.subscriptions_id = su.subscriptions_id
WHERE su.start_date <= current_date AND su.end_date > current_date;


