);

CREATE TABLE artist_event (
    artist_event_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id integer NOT NULL REFERENCES artist ON DELETE RESTRICT,
    event_id integer NOT NULL REFERENCES events ON DELETE CASCADE,
